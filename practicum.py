print("Выберите модель, которая спрогнозирует банкротство предприятия:")
print("1) Пятифакторная модель Альтмана;\n2) Модель иркутской ГЭА\n3) Модель Таффлера")
modelbank=int(input("Введите номер модели: "))
if modelbank==1:
    print("Введите данные из бухгалтерской отчетности предприятия:")
    a=int(input("Введите оборотные активы (1200): "))
    b=int(input("Введите капитал и резервы (1300): "))
    c=int(input("Введите нераспределенную прибыль (непокрытый убыток) (1370): "))
    d=int(input("Введите долгосрочные обязательства (1400): "))
    e=int(input("Введите краткосрочные обязательства (1500): "))
    f=int(input("Введите баланс — итого активов (1600): "))
    print("Введите данные из отчета о финансовых результатах:")
    g=int(input("Введите выручку (2110): "))
    h=int(input("Введите прибыль (убыток) до налогообложения (2300): "))
    i=int(input("Введите проценты к уплате (2330): "))
    j=int(input("Введите чистую прибыль (убыток) (2400): "))
    altman=(0.717 * ((a - e) / f) + 0.847 * (c / f) + 3.107 * ((h + i) / f) + 0.420 * (b / (d + e)) + 0.998 * (g / f))
    print("Результат расчета модели Альтмана: ", round(altman, 2))
    if altman<1.23:
        print("Высокая вероятность банкротства")
    elif 1.23<=altman<=2.89:
        print("Зона неопределенности")
    else:
        print("Низкая вероятность банкротства")
elif modelbank==2:
    print("Введите данные из бухгалтерской отчетности предприятия:")
    aa=int(input("Введите оборотные активы (1200): "))
    bb=int(input("Введите капитал и резервы (1300): "))
    cc=int(input("Введите краткосрочные обязательства (1500): "))
    dd=int(input("Введите баланс — итого активов (1600): "))
    print("Введите данные из отчета о финансовых результатах:")
    ee=int(input("Введите выручку (2110): "))
    ff=int(input("Введите себестоимость продаж (2120): "))
    gg=int(input("Введите чистую прибыль (убыток) (2400): "))
    irkutsk=(8.38 * ((aa - cc) / dd) + (gg / bb) + 0.05 * (ee / dd) + 0.63 * (gg / ff))
    print("Результат расчета модели иркутской ГЭА: ", round(irkutsk, 2))
    if irkutsk<0:
        print("Максимальная вероятность банкротства (90-100%)")
    elif 0<=irkutsk<=0.18:
        print("Высокая вероятность банкротства (60-80%)")
    elif 0.18<irkutsk<=0.32:
        print("Средняя вероятность банкротства (30-50%)")
    else:
        print("Низкая вероятность банкротства (менее 10%)")
elif modelbank==3:
    print("Введите данные из бухгалтерского баланса предприятия:")
    aaa=int(input("Введите оборотные активы (1200): "))
    bbb=int(input("Введите долгосрочные обязательства (1400): "))
    ccc=int(input("Введите краткосрочные обязательства (1500): "))
    ddd=int(input("Введите баланс — итого активов (1600): "))
    print("Введите данные из отчета о финансовых результатах:")
    eee=int(input("Введите выручку (2110): "))
    fff=int(input("Введите прибыль (убыток) от продаж (2200): "))
    taffler=(0.53 * (fff / ccc) + 0.13 * (aaa / (bbb + ccc)) + 0.18 * ((bbb + ccc) / ddd) + 0.16 * (eee / ddd))
    print("Результат расчета модели Таффлера: ", round(taffler, 2))
    if taffler<0.2:
        print("Высокая вероятность банкротства")
    elif 0.2<=taffler<=0.3:
        print("Зона неопределенности")
    else:
        print("Хорошие перспективы для предприятия, финансовая устойчивость высокая")
else:
    print("Выбранная модель не существует. Пожалуйста, выберите модель из предложенного списка")